#!/usr/bin/env python3
"""
Fetch posters for titles in _data/filmography.yml via the TMDB API.

You need a free TMDB account and API key: https://www.themoviedb.org/settings/api
By using this you accept TMDB's terms, which require visible attribution:
"This website uses TMDB and the TMDB APIs but is not endorsed, certified,
or otherwise approved by TMDB." An attribution line is already prepared
(commented out) at the bottom of subtitles.md — uncomment it if you use
these images.

Usage:
    pip install requests pyyaml
    TMDB_API_KEY=your_key python3 scripts/fetch_posters.py

What it does:
  - reads _data/filmography.yml
  - searches TMDB (movie or tv endpoint based on the 'type' field)
  - downloads each poster (w500) to assets/posters/
  - writes _data/posters.yml mapping title -> filename
    (your filmography.yml is never modified; comments are safe)
  - reports every title it could not match, so nothing fails silently

Titles with an explicit 'poster:' field in filmography.yml are skipped —
manual choices always win.
"""

import os
import re
import sys
import unicodedata

try:
    import requests
    import yaml
except ImportError:
    sys.exit("Missing dependencies. Run: pip install requests pyyaml")

API_KEY = os.environ.get("TMDB_API_KEY")
if not API_KEY:
    sys.exit("Set TMDB_API_KEY. Get a free key at themoviedb.org/settings/api")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "_data", "filmography.yml")
OUT_DIR = os.path.join(ROOT, "assets", "posters")
MAP_FILE = os.path.join(ROOT, "_data", "posters.yml")
IMG_BASE = "https://image.tmdb.org/t/p/w500"

os.makedirs(OUT_DIR, exist_ok=True)


def slugify(text):
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    text = re.sub(r"[^a-zA-Z0-9]+", "-", text).strip("-").lower()
    return text or "untitled"


def first_year(value):
    m = re.search(r"\d{4}", str(value or ""))
    return m.group(0) if m else None


def search_tmdb(title, year, kind):
    endpoint = "tv" if kind == "series" else "movie"
    params = {"api_key": API_KEY, "query": title}
    if year:
        params["first_air_date_year" if endpoint == "tv" else "year"] = year
    r = requests.get(f"https://api.themoviedb.org/3/search/{endpoint}",
                     params=params, timeout=20)
    r.raise_for_status()
    results = r.json().get("results", [])
    if not results and year:
        # retry without the year constraint
        params.pop("year", None)
        params.pop("first_air_date_year", None)
        r = requests.get(f"https://api.themoviedb.org/3/search/{endpoint}",
                         params=params, timeout=20)
        r.raise_for_status()
        results = r.json().get("results", [])
    return results[0] if results else None


def main():
    with open(DATA, encoding="utf-8") as f:
        works = yaml.safe_load(f)

    # Existing mappings are preserved — only new/unmapped titles are fetched.
    mapping = {}
    if os.path.exists(MAP_FILE):
        with open(MAP_FILE, encoding="utf-8") as f:
            mapping = yaml.safe_load(f) or {}
    missing = []

    for work in works:
        title = work["title"]
        if work.get("poster"):
            print(f"skip (manual poster set): {title}")
            continue
        if title in mapping:
            print(f"skip (already mapped): {title}")
            continue
        result = search_tmdb(title, first_year(work.get("year")),
                             work.get("type", "film"))
        poster_path = result.get("poster_path") if result else None
        if not poster_path:
            missing.append(title)
            print(f"NOT FOUND: {title}")
            continue

        fname = slugify(title) + ".jpg"
        dest = os.path.join(OUT_DIR, fname)
        img = requests.get(IMG_BASE + poster_path, timeout=30)
        img.raise_for_status()
        with open(dest, "wb") as f:
            f.write(img.content)
        found_name = result.get("title") or result.get("name", "?")
        print(f"ok: {title}  ->  {fname}  (matched: {found_name})")
        mapping[title] = fname

    with open(MAP_FILE, "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/fetch_posters.py — safe to edit by hand.\n")
        f.write("# Maps filmography titles to files in /assets/posters/.\n")
        yaml.safe_dump(mapping, f, allow_unicode=True, sort_keys=True)

    print(f"\n{len(mapping)} posters saved, {len(missing)} not found.")
    if missing:
        print("Not matched (add manually or fix the title/year):")
        for t in missing:
            print(f"  - {t}")
    print("\nCHECK EVERY MATCH — search-by-title can pick the wrong film")
    print("(remakes, same-name titles). Open assets/posters/ and eyeball them.")
    print("Then uncomment the TMDB attribution line in subtitles.md.")


if __name__ == "__main__":
    main()
